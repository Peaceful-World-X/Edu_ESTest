% 输入数据数组，包含20个测量值和两个显著高峰
input_data = [1.0, 1.1, 1.2, 1.3, 1.4, 10.0, 1.5, 1.6, 1.7, 1.8, ...
              2.0, 2.1, -20.0, 2.2, 2.3, 2.4, 2.5, 2.6, 2.7, 2.8];

% 移动平均滤波结果
moving_average_result = [1.00, 1.10, 1.20, 1.30, 1.20, 3.00, 3.08, 3.16, 3.24, 3.32, 1.72, 1.84, -2.48, -2.38, -2.28, -2.20, -2.12, 2.40, 2.50, 2.60];

% 指数加权移动平均滤波结果
ewma_result = [1.00, 1.03, 1.08, 1.15, 1.22, 3.86, 3.15, 2.68, 2.39, 2.21, 2.15, 2.13, -4.51, -2.49, -1.06, -0.02, 0.74, 1.30, 1.72, 2.04];

% 中值滤波结果
median_result = [1.00, 1.10, 1.20, 1.30, 1.20, 1.30, 1.40, 1.60, 1.50, 1.60, 1.70, 1.80, 2.00, 2.10, 2.00, 2.20, 2.30, 2.40, 2.50, 2.60];

% 数据长度
len = length(input_data);

% 创建x轴，表示时间步长或数据点索引
x = 1:len;

% 绘制原始数据图像
figure; % 打开新图窗口
plot(x, input_data, '-ko', 'LineWidth', 2, 'MarkerSize', 6); 
hold on;

% 绘制移动平均滤波结果
plot(x, moving_average_result, '-b*', 'LineWidth', 1.5, 'MarkerSize', 6); 

% 绘制指数加权移动平均滤波结果
plot(x, ewma_result, '-g^', 'LineWidth', 1.5, 'MarkerSize', 6); 

% 绘制中值滤波结果
plot(x, median_result, '-rs', 'LineWidth', 1.5, 'MarkerSize', 6); 

% 图形配置
title('输入数据及三种滤波器的滤波效果');
xlabel('数据点索引');
ylabel('测量值');
legend('原始数据', '移动平均滤波', '指数加权移动平均滤波', '中值滤波');
grid on;

% 设置绘图的轴范围
ylim([-25, 15]);
